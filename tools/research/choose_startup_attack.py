"""Submit one native Outburst per dedicated client using guarded ADB UI taps.

No HTTP ready/move is generated by this tool; Android handles the UI action.
Only the retained registration-party capture and 1280x720 layout are supported.
"""
import argparse
from datetime import datetime, timezone
import hashlib
import io
import json
from pathlib import Path
import sys
import time

from startup_capture_device import Device, ROOT
import android_startup_fixture as fixture
sys.path.insert(0, str(ROOT / '.research/python'))
from PIL import Image


def menu(data, attack=False):
    with Image.open(io.BytesIO(data)) as image:
        if image.size != (1280, 720):
            return False
        image = image.convert('RGB')
        r, g, b = image.getpixel((1130, 520) if attack else (1000, 550))
        return r > 180 and g < 100 and b < 200 if attack else r < 100 and g > 150 and b > 150


def run(manifest, output, wait):
    private = (ROOT / '.research').resolve()
    manifest, output = manifest.resolve(), output.resolve()
    if not manifest.is_relative_to(private) or not output.is_relative_to(private):
        raise ValueError('Ignored research paths required')
    output.mkdir(parents=True, exist_ok=False)
    devices = {role: Device(role) for role in ('primary', 'peer')}
    for device in devices.values():
        device.verify()
    stop = time.monotonic() + wait
    while time.monotonic() < stop:
        f = json.loads(manifest.read_text())
        if f.get('battle'):
            state = fixture.status(f)['startup']
            if state['state'] == 'READY':
                if float(state['deadline_remaining_seconds']) < 20:
                    raise RuntimeError('Too little fixed lease remains for guarded input')
                break
            if state['state'] == 'CANCELLED':
                raise RuntimeError('Startup already ended')
        time.sleep(.5)
    else:
        raise RuntimeError('Both native ready signals did not arrive in time')
    fixture.guard(f)
    proof = {'input_kind': 'ADB UI taps; no scripted HTTP selection', 'roles': {}}
    for role, account in zip(devices, f['before']['accounts']):
        owned = [m for m in f['before']['owned']['owned_morties'] if m['player_id'] == account['player_id']]
        assert len(owned) == 1 and owned[0]['morty_id'] == 'MortyDefault'
        attacks = [a for a in f['before']['owned']['owned_attacks'] if a['owned_morty_id'] == owned[0]['owned_morty_id']]
        assert len(attacks) == 1 and attacks[0]['attack_id'] == 'AttackOutburst' and int(attacks[0]['position']) == 0 and int(attacks[0]['pp']) > 0
        device = devices[role]
        before = device.adb('exec-out', 'screencap', '-p').stdout
        (output / (role + '-before.png')).write_bytes(before)
        if not menu(before):
            raise RuntimeError('Native battle main menu not recognized')
        device.adb('shell', 'input', 'tap', '250', '560')
        until = time.monotonic() + 4
        while True:
            shot = device.adb('exec-out', 'screencap', '-p').stdout
            if menu(shot, True):
                break
            if time.monotonic() >= until:
                raise RuntimeError('Native attack menu not recognized; no attack tapped')
            time.sleep(.2)
        (output / (role + '-attack-menu.png')).write_bytes(shot)
        proof['roles'][role] = {'tap_utc': datetime.now(timezone.utc).isoformat(), 'attack': 'AttackOutburst',
                                'menu_sha256': hashlib.sha256(shot).hexdigest()}
        device.adb('shell', 'input', 'tap', '170', '550')
        time.sleep(.4)
        (output / (role + '-waiting.png')).write_bytes(device.adb('exec-out', 'screencap', '-p').stdout)
    state = fixture.status(f)['startup']
    assert state['selection_count'] == 2 and state['pair_count'] == 1
    assert state['retired_selection_count'] == state['retired_pair_count'] == 0
    fixture.guard(f)
    proof['paired'] = True
    (output / 'input-manifest.json').write_text(json.dumps(proof, indent=2) + '\n')
    print('Both native UI selections stored; immutable pair exists; persistent save guard passes.')


if __name__ == '__main__':
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--fixture', type=Path, required=True)
    p.add_argument('--output', type=Path, required=True)
    p.add_argument('--wait', type=int, default=60, choices=range(10, 121))
    args = p.parse_args()
    run(args.fixture, args.output, args.wait)
